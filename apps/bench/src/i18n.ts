let current: Lang = (localStorage.getItem("bench.lang") as Lang | null) ?? (navigator.language.toLowerCase().startsWith("de") ? "de" : "en");

export const lang = () => current;

export function setLang(next: Lang): void {
  current = next;
  localStorage.setItem("bench.lang", next);
  document.documentElement.lang = next;
}

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const text: string = (current === "de" ? de : en)[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

/** A bilingual text from the data. */
export const tx = (text: Text | string | undefined) => (typeof text === "string" ? text : text?.[current] || text?.de || "");
